# Writes test/fixtures/font_info.exs: what fontTools reads from each test font, which is what
# `Pica.info/1` must report.
#
# Run from the repository root:
#
#   docker run --rm -v "$PWD":/work -w /work -e OWNER="$(id -u):$(id -g)" python:3.12-slim sh -c \
#     'pip install --quiet fonttools==4.67.0 brotli==1.2.0 \
#      && python -I test/support/ground_truth/font_info.py && chown "$OWNER" test/fixtures/font_info.exs'
#
# Rerun it when a test font changes. The names follow fontTools' `getDebugName`: the first record
# for the name ID that is Macintosh English or Windows US English, else the last record that
# decodes; the family is name ID 16 (typographic family) when present, else 1, and the subfamily
# 17, else 2.

import os
import platform

import fontTools
from fontTools.ttLib import TTFont

FONTS = "test/fonts"
TARGET = "test/fixtures/font_info.exs"

CONTAINERS = {
    b"\x00\x01\x00\x00": "sfnt",
    b"true": "sfnt",
    b"OTTO": "sfnt",
    b"ttcf": "collection",
    b"wOFF": "woff",
    b"wOF2": "woff2",
}


def container(path):
    with open(path, "rb") as file:
        return CONTAINERS[file.read(4)]


def font_count(path, kind):
    if kind != "collection":
        return 1
    with open(path, "rb") as file:
        header = file.read(12)
    return int.from_bytes(header[8:12], "big")


def outlines(font):
    for tag, kind in (("glyf", "truetype"), ("CFF ", "cff"), ("CFF2", "cff2")):
        if tag in font:
            return kind
    raise ValueError("no outline table")


def info(path, index):
    kind = container(path)
    font = TTFont(path, fontNumber=index) if kind == "collection" else TTFont(path)
    name = font["name"]
    os2 = font["OS/2"] if "OS/2" in font else None
    hhea = font["hhea"]
    axes = (
        [
            {
                "tag": axis.axisTag,
                "minimum": float(axis.minValue),
                "default": float(axis.defaultValue),
                "maximum": float(axis.maxValue),
            }
            for axis in font["fvar"].axes
        ]
        if "fvar" in font
        else []
    )
    italic = bool(os2.fsSelection & 1) if os2 else bool(font["head"].macStyle & 2)
    return {
        "file": os.path.basename(path),
        "index": index,
        "font_count": font_count(path, kind),
        "container": Atom(kind),
        "outlines": Atom(outlines(font)),
        "family": name.getDebugName(16) or name.getDebugName(1) or Atom("none"),
        "subfamily": name.getDebugName(17) or name.getDebugName(2) or Atom("none"),
        "units_per_em": font["head"].unitsPerEm,
        "ascender": hhea.ascent,
        "descender": hhea.descent,
        "line_gap": hhea.lineGap,
        "weight_class": os2.usWeightClass if os2 else Atom("none"),
        "italic": italic,
        "glyph_count": font["maxp"].numGlyphs,
        "axes": axes,
    }


class Atom(str):
    pass


def elixir(value, indent=""):
    inner = indent + "  "
    if isinstance(value, Atom):
        return ":" + value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("#{", "\\#{")
        return '"' + escaped + '"'
    if isinstance(value, list):
        if not value:
            return "[]"
        items = (",\n" + inner).join(elixir(item, inner) for item in value)
        return "[\n" + inner + items + "\n" + indent + "]"
    if isinstance(value, dict):
        pairs = (",\n" + inner).join(
            key + ": " + elixir(item, inner) for key, item in value.items()
        )
        return "%{\n" + inner + pairs + "\n" + indent + "}"
    raise TypeError(type(value))


entries = []
for file in sorted(os.listdir(FONTS)):
    path = os.path.join(FONTS, file)
    try:
        kind = container(path)
    except KeyError:
        continue  # a licence or FONTS.md
    for index in range(font_count(path, kind)):
        entries.append(info(path, index))

os.makedirs(os.path.dirname(TARGET), exist_ok=True)
with open(TARGET, "w") as output:
    output.write(
        "# Generated by test/support/ground_truth/font_info.py with fontTools "
        + fontTools.version
        + " on Python "
        + platform.python_version()
        + "; do not edit.\n"
    )
    output.write(elixir(entries) + "\n")
